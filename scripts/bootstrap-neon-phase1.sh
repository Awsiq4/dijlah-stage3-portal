#!/usr/bin/env bash
# Phase 1.2 local bootstrap against the EXISTING Neon test database (dijlah-stage3-portal-test / neondb).
# Non-destructive only: idempotent schema, super-admin bootstrap, seed INSERT-ONLY migration.
# Secrets come from the environment or .env.local (gitignored) and are never printed or committed.
set -euo pipefail
cd "$(dirname "$0")/.."

if [ -f .env.local ]; then set -a; source ./.env.local; set +a; fi

if [ -z "${DATABASE_URL:-}" ]; then
  echo "ERROR: DATABASE_URL is not set. Put it in .env.local (gitignored) or export it."
  echo "Get it from the Neon dashboard (pooled connection string). It is never requested in chat."
  exit 1
fi

echo "== 1/4 applying schemas (idempotent, non-destructive) =="
node --experimental-strip-types scripts/apply-portal-schema.mjs

echo "== 2/4 super admin bootstrap =="
if [ -z "${SUPER_ADMIN_EMAIL:-}" ]; then
  echo "ERROR: SUPER_ADMIN_EMAIL is not set (in .env.local or env)."
  exit 1
fi
if [ -z "${SUPER_ADMIN_PASSWORD:-}" ]; then
  pw="$(node -e "console.log(require('node:crypto').randomBytes(18).toString('base64url'))")"
  printf '\n# generated by bootstrap-neon-phase1.sh — rotate after first login\nSUPER_ADMIN_PASSWORD=%s\n' "$pw" >> .env.local
  export SUPER_ADMIN_PASSWORD="$pw"
  echo "A random SUPER_ADMIN_PASSWORD was generated into .env.local (gitignored) — the value is NOT printed here. Rotate it after first login."
fi
npm run create:super-admin

echo "== 3/4 seed migration (INSERT-ONLY default; existing rows are preserved) =="
npm run migrate:seed

echo "== 4/4 optional real-DB E2E test =="
echo "Run: npm run test:e2e   (sign-in -> publish -> public visibility -> section targeting -> edit -> audit -> delete, bot stays disabled)"
echo "Bootstrap complete. Telegram remains disabled (TELEGRAM_BOT_ENABLED unset/false)."
